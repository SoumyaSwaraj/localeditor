"""Build the twenty LocalEditor originals.

  python tools/typefoundry/build_all.py [--only slug,slug] [--ttf-dir DIR] [--jobs N]

Writes assets/fonts/originals/<slug>/{<slug>-400.woff2,<slug>-700.woff2,LICENSE,family.json}
and assets/data/fonts-originals.json. TTF masters go to --ttf-dir (default: a build
folder outside the shipped tree). Every instance is checked with the OpenType Sanitizer
(the same checker Chrome and Firefox use).
"""
import argparse
import json
import os
import subprocess
import tempfile
import sys
from concurrent.futures import ProcessPoolExecutor

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
sys.path.insert(0, HERE)

from families import FAMILIES, slug, params  # noqa: E402

WEIGHTS = [('Regular', 400), ('Bold', 700)]
OUT = os.path.join(ROOT, 'assets', 'fonts', 'originals')
LICENSE = """LocalEditor Originals: {name}
Copyright (c) 2026 LocalEditor. All rights reserved.

This typeface is original work generated by the LocalEditor parametric type
generator (tools/typefoundry). No outlines were copied from any existing font.

It is bundled for use within LocalEditor: you may use it in designs you make with
LocalEditor and in the files you export from it (images, PDFs and prints), for
personal and commercial work, without attribution.

Redistributing the font files themselves, or using them outside LocalEditor, is not
permitted while the owner decides on a public licence (for example the SIL Open Font
License 1.1).
"""


def build_one(job):
    fam, weight, wnum, ttf_dir = job
    from tf.build import build_font
    from fontTools.ttLib import TTFont
    s = slug(fam['name'])
    os.makedirs(os.path.join(OUT, s), exist_ok=True)
    os.makedirs(ttf_dir, exist_ok=True)
    ttf = os.path.join(ttf_dir, '%s-%d.ttf' % (s, wnum))
    info = build_font(fam, weight, params(fam, weight), ttf)
    f = TTFont(ttf)
    f.flavor = 'woff2'
    w2 = os.path.join(OUT, s, '%s-%d.woff2' % (s, wnum))
    f.save(w2)
    f = TTFont(ttf)
    f.flavor = 'woff'
    w1 = os.path.join(OUT, s, '%s-%d.woff' % (s, wnum))
    f.save(w1)
    ots = subprocess.run([sys.executable, '-m', 'ots', ttf], capture_output=True, text=True)
    ots2 = subprocess.run([sys.executable, '-m', 'ots', w2], capture_output=True, text=True)
    return dict(slug=s, weight=wnum, ttf=ttf, woff2=w2, woff=w1, glyphs=info['glyphs'], pairs=info['pairs'],
                woff2_bytes=os.path.getsize(w2), ttf_bytes=os.path.getsize(ttf), woff_bytes=os.path.getsize(w1),
                ots=(ots.returncode, (ots.stdout + ots.stderr).strip()[:300]), ots_woff2=(ots2.returncode, (ots2.stdout + ots2.stderr).strip()[:300]))


def family_json(fam, results, P):
    s = slug(fam['name'])
    files = {str(r['weight']): {'woff2': 'assets/fonts/originals/%s/%s' % (s, os.path.basename(r['woff2'])),
                                'woff': 'assets/fonts/originals/%s/%s' % (s, os.path.basename(r['woff']))} for r in results}
    return dict(
        family=fam['name'], slug=s, source='localeditor', version='1.000',
        intent=fam['intent'], feel=fam['feel'], description=fam['description'], uses=fam['uses'], concept=fam['concept'],
        category='serif' if fam['regular'].get('serif', 'none') != 'none' else 'sans',
        weights=[400, 700], italic=False, license='LocalEditor-Proprietary (pending owner decision)',
        files=files,
        bytes={str(r['weight']): {'woff2': r['woff2_bytes'], 'woff': r['woff_bytes']} for r in results},
        metrics=dict(unitsPerEm=1000, ascender=950, descender=-250, lineGap=0, capHeight=P['cap'], xHeight=P['xh']),
        parameters=dict(regular=fam['regular'], bold=fam['bold']),
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--only', default='')
    ap.add_argument('--ttf-dir', default=os.path.join(tempfile.gettempdir(), 'typefoundry-build'))
    ap.add_argument('--jobs', type=int, default=3)
    ap.add_argument('--no-manifest', action='store_true')
    a = ap.parse_args()
    only = set(x for x in a.only.split(',') if x)
    fams = [f for f in FAMILIES if not only or slug(f['name']) in only]
    jobs = [(f, w, n, a.ttf_dir) for f in fams for (w, n) in WEIGHTS]
    with ProcessPoolExecutor(max_workers=a.jobs) as ex:
        res = list(ex.map(build_one, jobs))
    bad = [r for r in res if r['ots'][0] != 0 or r['ots_woff2'][0] != 0]
    from tf.style import DEFAULTS
    for f in fams:
        rs = [r for r in res if r['slug'] == slug(f['name'])]
        P = dict(DEFAULTS)
        P.update(f['regular'])
        meta = family_json(f, rs, P)
        d = os.path.join(OUT, slug(f['name']))
        with open(os.path.join(d, 'family.json'), 'w') as fh:
            json.dump(meta, fh, indent=1, default=list)
            fh.write('\n')
        with open(os.path.join(d, 'LICENSE'), 'w') as fh:
            fh.write(LICENSE.format(name=f['name']))
    for r in res:
        print('%-12s %d  glyphs=%d kern=%d woff2=%6d woff=%6d ttf=%6d  ots=%s/%s' % (r['slug'], r['weight'], r['glyphs'], r['pairs'], r['woff2_bytes'], r['woff_bytes'], r['ttf_bytes'], r['ots'][0], r['ots_woff2'][0]))
    if bad:
        for r in bad:
            print('OTS FAILED', r['slug'], r['weight'], r['ots'], r['ots_woff2'])
        sys.exit(1)
    if not a.no_manifest and not only:
        write_manifest()


def write_manifest():
    import page
    page.write(FAMILIES)
    fams = []
    for f in FAMILIES:
        with open(os.path.join(OUT, slug(f['name']), 'family.json')) as fh:
            m = json.load(fh)
        fams.append({k: m[k] for k in ('family', 'slug', 'source', 'version', 'intent', 'feel', 'description', 'uses', 'category', 'weights', 'italic', 'license', 'files', 'bytes')})
    out = dict(generated='tools/typefoundry/build_all.py', source='localeditor', collection='LocalEditor originals',
               research='docs/research/typeface-psychology.md', families=fams)
    with open(os.path.join(ROOT, 'assets', 'data', 'fonts-originals.json'), 'w') as fh:
        json.dump(out, fh, indent=1)
        fh.write('\n')
    # the shim carries a compact copy so LE.fonts.list() stays synchronous
    shim = os.path.join(ROOT, 'assets', 'js', 'le-fonts-originals.js')
    if os.path.exists(shim):
        compact = [{k: f[k] for k in ('family', 'slug', 'intent', 'feel', 'description', 'category', 'weights', 'files')} for f in fams]
        src = open(shim).read()
        a, b = '/* BEGIN originals manifest */', '/* END originals manifest */'
        i, j = src.index(a) + len(a), src.index(b)
        src = src[:i] + '\n  var ORIGINALS = ' + json.dumps(compact, separators=(',', ':')) + ';\n  ' + src[j:]
        open(shim, 'w').write(src)


if __name__ == '__main__':
    main()
