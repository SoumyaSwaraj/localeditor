cases['pick is quality first, then speed, under emulated device capabilities'] = async ({ browser, base, h }) => {
  const page = await h.open(browser, base, '/', 'desktop');
  await ready(page);
  await page.waitForFunction(() => window.LE && LE.support && LE.support.check);
  const r = await page.evaluate(() => {
    const S = LE.support;
    [['t.gpu', ['webgpu']], ['t.wasm', ['wasm']], ['t.wasm2', ['wasm']], ['t.lo', []]].forEach(([id, needs]) => S.define({ id, name: id, needs, wants: [], memoryMB: 0, downloadMB: 0 }));
    const opts = (cached) => [
      { id: 'gpu', quality: 4, speed: 'fast', bytes: 30e6, supportId: 't.gpu', cached: false },
      { id: 'det', quality: 3, speed: 'medium', bytes: 44e6, supportId: 't.wasm', cached: !!cached.det },
      { id: 'det-fast', quality: 3, speed: 'fast', bytes: 45e6, supportId: 't.wasm2', cached: !!cached.detf },
      { id: 'quick', quality: 1, speed: 'fast', bytes: 5e6, supportId: 't.lo', cached: !!cached.quick }
    ];
    const ids = (p) => [p.now && p.now.id, p.next && p.next.id];
    const out = {};
    S.override('webgpu', true); S.override('wasm', true);
    out.allOk = ids(LE.downloads.pick(opts({ quick: 1 })));
    S.override('webgpu', false);
    out.noGpu = ids(LE.downloads.pick(opts({ quick: 1 })));
    out.noGpuCached = ids(LE.downloads.pick(opts({ quick: 1, det: 1 })));
    out.nothingCached = ids(LE.downloads.pick(opts({})));
    S.override('wasm', false);
    out.onlyQuick = ids(LE.downloads.pick(opts({})));
    S.override('webgpu', undefined); S.override('wasm', undefined);
    out.empty = ids(LE.downloads.pick([]));
    return out;
  });
  h.assert.equal(JSON.stringify(r.allOk), JSON.stringify(['quick', 'gpu']), 'use what is here, fetch the best for next time');
  h.assert.equal(JSON.stringify(r.noGpu), JSON.stringify(['quick', 'det-fast']), 'unsupported best is skipped; a tie on quality goes to the faster');
  h.assert.equal(JSON.stringify(r.noGpuCached), JSON.stringify(['det', 'det-fast']), 'a cached option of top quality is used now; never a lower one');
  h.assert.equal(JSON.stringify(r.nothingCached), JSON.stringify(['det-fast', null]), 'nothing cached: the best downloadable within the limit');
  h.assert.equal(JSON.stringify(r.onlyQuick), JSON.stringify(['quick', null]), 'only what the device can run');
  h.assert.equal(JSON.stringify(r.empty), JSON.stringify([null, null]), 'no options');
};

