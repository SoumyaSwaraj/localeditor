const TYPES = { '.html': 'text/html; charset=utf-8', '.js': 'text/javascript; charset=utf-8', '.css': 'text/css; charset=utf-8', '.json': 'application/json', '.webmanifest': 'application/manifest+json', '.svg': 'image/svg+xml', '.png': 'image/png', '.jpg': 'image/jpeg', '.webp': 'image/webp', '.woff2': 'font/woff2', '.wasm': 'application/wasm' };

async function ready(page) {
  await page.waitForFunction(() => window.LE && LE.downloads && LE.downloads.__real, null, { timeout: 15000 });
  await page.evaluate(() => LE.downloads.ready);
}
/* Starts a request without waiting for it; the result lands in window.__r. */
function start(page, item) {
  return page.evaluate((it) => { window.__r = null; LE.downloads.request(it).then((r) => { window.__r = r; }); }, item);
}
async function result(page) { await page.waitForFunction(() => window.__r, null, { timeout: 10000 }); return page.evaluate(() => window.__r); }
const asked = (page) => page.evaluate(() => !!document.querySelector('dialog.ld-ask[open]'));
async function shot(page, name) { if (SHOTS) { fs.mkdirSync(SHOTS, { recursive: true }); await page.screenshot({ path: path.join(SHOTS, name + '.png') }); } }

/* A static server whose /sw.js is generated by scripts/build.js; `slow` delays listed paths so a download can be caught mid-way. */
function serveWorker(slow, opts) {
  opts = opts || {};
  const state = { version: 'dl-1' };
  return new Promise((resolve) => {
    const server = http.createServer((req, res) => {
      let p = decodeURIComponent(req.url.split('?')[0]);
      if (p === '/sw.js') { res.writeHead(200, { 'Content-Type': 'text/javascript; charset=utf-8', 'Cache-Control': 'no-store' }); res.end(build.swSource({ version: state.version, expert: opts.expert })); return; }
      if (opts.virtual && opts.virtual[p]) { res.writeHead(200, { 'Content-Type': 'text/javascript; charset=utf-8', 'Cache-Control': 'no-store' }); res.end(opts.virtual[p]); return; }
      if (p.endsWith('/')) p += 'index.html';
      const file = path.join(ROOT, p);
      if (!file.startsWith(ROOT)) { res.writeHead(403); res.end(); return; }
      fs.readFile(file, (err, buf) => {
        if (err) { res.writeHead(404); res.end('Not found'); return; }
        const send = () => { res.writeHead(200, { 'Content-Type': TYPES[path.extname(file).toLowerCase()] || 'application/octet-stream', 'Cache-Control': 'no-store', 'Content-Length': buf.length }); res.end(buf); };
        const ms = slow && Object.keys(slow).filter((k) => p.indexOf(k) >= 0).map((k) => slow[k])[0];
        if (ms) setTimeout(send, ms); else send();
      });
    });
    server.listen(0, '127.0.0.1', () => resolve({ server, state, base: 'http://127.0.0.1:' + server.address().port }));
  });
}
/* Polls an async page function until it returns true. */
async function until(page, fn, ms, msg) {
  const end = Date.now() + (ms || 15000);
  for (;;) {
    if (await page.evaluate(fn).catch(() => false)) return;
    if (Date.now() > end) throw new Error('Timed out: ' + (msg || fn.toString().slice(0, 80)));
    await new Promise((r) => setTimeout(r, 500));
  }
}
async function controlled(page) {
  await page.waitForFunction(() => navigator.serviceWorker && navigator.serviceWorker.controller, null, { timeout: 30000 });
  await page.waitForFunction(() => caches.keys().then((k) => k.some((n) => n.indexOf('le-app-') === 0)), null, { timeout: 30000 });
}

