cases['pack manifest matches the files and the 25 MB decision is applied and guarded'] = async ({ h }) => {
  const disk = JSON.parse(fs.readFileSync(path.join(ROOT, 'assets/data/packs.json'), 'utf8'));
  const now = build.packsJSON();
  /* The decision must match exactly; sizes within 5% or 512 KB (code changes every day; a stale manifest near the line still fails on the decision). */
  ['basicFirstVisit', 'expertWithBasic'].forEach((k) => h.assert.equal(disk.decision[k], now.decision[k], 'packs.json decision "' + k + '" is out of date: run node scripts/build.js'));
  disk.packs.forEach((p) => {
    const q = now.packs.find((x) => x.id === p.id);
    ['raw', 'gzip', 'transfer'].forEach((k) => h.assert(Math.abs(p[k] - q[k]) <= Math.max(512 * 1024, q[k] * 0.05), 'packs.json ' + p.id + ' ' + k + ' is stale (' + p[k] + ' vs ' + q[k] + '): run node scripts/build.js'));
  });
  const d = now.decision, limit = build.WHOLE_EDITOR_LIMIT;
  h.assert.equal(limit, 25 * MB, 'the owner\'s threshold');
  h.assert.equal(d.basicFirstVisit, d.basicTransfer < limit, 'Basic decision follows its size');
  h.assert.equal(d.expertWithBasic, d.basicFirstVisit && d.basicPlusExpertTransfer < limit, 'Basic + Expert decision follows its size');
  const byId = {};
  now.packs.forEach((p) => { byId[p.id] = p; });
  ['basic', 'basic+models', 'expert', 'all'].forEach((id) => h.assert(byId[id] && !byId[id].hidden, 'pack ' + id));
  /* Every listed file exists with its size; totals add up; transfer never exceeds raw. */
  ['basic', 'expert', 'models'].forEach((id) => {
    const p = byId[id];
    let raw = 0;
    p.files.forEach((f) => {
      const file = path.join(ROOT, f.u.slice(2).replace(/\/$/, '/index.html'));
      h.assert(fs.existsSync(file), 'missing ' + f.u);
      if (id === 'models') h.assert.equal(fs.statSync(file).size, f.raw, 'size of ' + f.u + ' (downloads are verified against it)');
      raw += f.raw;
      h.assert(f.transfer <= f.raw && f.gzip > 0, 'transfer of ' + f.u);
    });
    h.assert.equal(p.raw, raw, id + ' raw total');
    h.assert.equal(p.count, p.files.length, id + ' file count');
  });
  h.assert.equal(byId['basic+models'].transfer, byId.basic.transfer + byId.models.transfer, 'combination adds up');
  h.assert(byId.models.files.some((f) => f.u === './assets/models/u2netp.onnx' && f.model === 'u2netp'), 'models carry their storage-manager id');
  h.assert(byId.models.files.some((f) => /ocr\/eng\.traineddata$/.test(f.u) && f.model === 'ocr-eng'), 'English OCR data is a model');
  /* The worker gets exactly what the decision says. */
  const pre = build.precacheList();
  h.assert(byId.basic.files.every((f) => pre.includes(f.u)) === d.basicFirstVisit, 'Basic is precached on the first visit exactly when it is under 25 MB');
  h.assert(byId.expert.files.every((f) => pre.includes(f.u)) === (d.expertWithBasic || !byId.expert.files.length), 'Expert joins the first visit exactly when Basic + Expert is under 25 MB');
  h.assert(!pre.some((u) => build.MODELS.test(u.slice(2))), 'models never join the first visit');
  /* Forced split: the Expert files leave the precache and the worker adds them once the pack marker exists. */
  process.env.LE_PACK_DECISION = 'split';
  try {
    const split = build.precacheList();
    h.assert(!split.some((u) => build.EXPERT.test(u.slice(2))), 'split keeps Expert out of the first download');
    const src = build.swSource({ version: 'x', expert: ['./assets/js/expert/a.js'] });
    new Function(src);
    h.assert(/__packs\/expert/.test(src) && src.indexOf('"./assets/js/expert/a.js"') > 0, 'worker knows the on-demand Expert files');
  } finally { delete process.env.LE_PACK_DECISION; }
  h.assert(/le-packs-v1/.test(build.swSource({ version: 'x' })), 'worker keeps the pack markers');
};

