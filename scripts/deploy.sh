#!/usr/bin/env bash
# Deploy LocalEditor to S3 behind CloudFront.
#
#   scripts/deploy.sh --bucket my-bucket --distribution E123ABC [--profile name] [--dry-run] [--delete] [--full] [--skip-build]
#
# Or set LE_BUCKET / LE_DISTRIBUTION / AWS_PROFILE in the environment. See docs/DEPLOY.md.
#
#   --dry-run     Show what would be uploaded, deleted and invalidated. Changes nothing.
#                 Works without the AWS CLI installed (prints the commands instead).
#   --delete      Also delete files from the bucket that are no longer in the site.
#   --full        Re-upload every file (use after changing cache headers or content types;
#                 a normal sync skips files whose size and date did not change).
#   --skip-build  Do not run `node scripts/build.js` first.
#
# Upload order matters: long-lived assets first, code next, pages and the service worker last,
# so a visitor never gets a new page that points at a file that is not there yet.
set -euo pipefail

BUCKET="${LE_BUCKET:-}"
DIST="${LE_DISTRIBUTION:-}"
PROFILE="${AWS_PROFILE:-}"
DRY=0
DELETE=0
FULL=0
BUILD=1

while [ $# -gt 0 ]; do
  case "$1" in
    --bucket) BUCKET="$2"; shift 2 ;;
    --distribution) DIST="$2"; shift 2 ;;
    --profile) PROFILE="$2"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    --delete) DELETE=1; shift ;;
    --full) FULL=1; shift ;;
    --skip-build) BUILD=0; shift ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1 (try --help)" >&2; exit 2 ;;
  esac
done

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

if [ -z "$BUCKET" ]; then echo "Missing --bucket (or LE_BUCKET)." >&2; exit 2; fi
case "$BUCKET" in s3://*) BUCKET="${BUCKET#s3://}" ;; esac
if ! [[ "$BUCKET" =~ ^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$ ]]; then echo "That does not look like an S3 bucket name: $BUCKET" >&2; exit 2; fi
if [ -z "$DIST" ]; then echo "Note: no --distribution given, so CloudFront will not be invalidated." >&2; fi

HAVE_AWS=1
command -v aws >/dev/null 2>&1 || HAVE_AWS=0
if [ "$HAVE_AWS" = 0 ] && [ "$DRY" = 0 ]; then echo "The AWS CLI is not installed. Install it (docs/DEPLOY.md, step 2) or use --dry-run." >&2; exit 1; fi

AWS=(aws)
[ -n "$PROFILE" ] && AWS+=(--profile "$PROFILE")

# Runs a command, or prints it when there is no AWS CLI during a dry run.
run() {
  if [ "$HAVE_AWS" = 0 ]; then printf '  would run:'; printf ' %q' "$@"; printf '\n'; return 0; fi
  "$@"
}

if [ "$BUILD" = 1 ]; then
  echo "== Building (service worker, manifest, sitemap)"
  node scripts/build.js
fi
for f in sw.js manifest.webmanifest index.html offline.html; do
  [ -f "$f" ] || { echo "Missing $f. Run node scripts/build.js." >&2; exit 1; }
done
node -e "JSON.parse(require('fs').readFileSync('manifest.webmanifest','utf8'))" || { echo "manifest.webmanifest is not valid JSON." >&2; exit 1; }
grep -q "le-app-" sw.js || { echo "sw.js was not generated by this version of scripts/build.js." >&2; exit 1; }
if [ -n "$(git status --porcelain 2>/dev/null | grep -v -E ' (sw\.js|sitemap\.xml)$' || true)" ]; then
  echo "Warning: the working tree has uncommitted changes; they will be deployed." >&2
fi

DEST="s3://$BUCKET"
VERB=(s3 sync)
[ "$FULL" = 1 ] && VERB=(s3 cp --recursive)
COMMON=(--only-show-errors --no-progress)
[ "$DRY" = 1 ] && COMMON=(--dryrun)

# Never uploaded: tooling, tests, docs, repo files.
NEVER=(--exclude ".git/*" --exclude ".claude/*" --exclude "node_modules/*" --exclude "scripts/*" --exclude "tests/*"
       --exclude "docs/*" --exclude "infra/*" --exclude "*.md" --exclude ".gitignore" --exclude ".nojekyll" --exclude "*.DS_Store")

# Cache classes. The service worker keeps installed copies fresh, so code only needs a short HTTP cache.
CC_PAGE="public, max-age=0, no-cache"
CC_CODE="public, max-age=600, must-revalidate"
CC_DATA="public, max-age=86400, stale-while-revalidate=604800"
CC_MONTH="public, max-age=2592000"
CC_YEAR="public, max-age=31536000, immutable"

# pass <cache-control> <content-type or ""> <include patterns...>
pass() {
  local cc="$1" ct="$2"; shift 2
  local inc=()
  for p in "$@"; do inc+=(--include "$p"); done
  local typ=()
  [ -n "$ct" ] && typ=(--content-type "$ct")
  echo "-- $cc ${ct:+($ct)}: $*"
  run "${AWS[@]}" "${VERB[@]}" . "$DEST" --exclude "*" "${inc[@]}" "${NEVER[@]}" --cache-control "$cc" "${typ[@]}" "${COMMON[@]}"
}

echo "== Uploading to $DEST$([ "$DRY" = 1 ] && echo ' (dry run)')"
# 1. Long-lived files whose content never changes under the same name.
pass "$CC_YEAR" "" "assets/fonts/*" "assets/photos/*" "assets/img/*"
pass "$CC_YEAR" "application/octet-stream" "assets/models/*.onnx" "assets/models/*.bin"
pass "$CC_YEAR" "application/wasm" "*.wasm"
pass "$CC_YEAR" "" "assets/models/*.json"
# 2. Vendor libraries, icons and screenshots: a month (names are stable, so not immutable).
pass "$CC_MONTH" "" "assets/vendor/*" "assets/icons/*" "assets/screenshots/*"
# 3. Graphics data (icon packs, collage layouts): a day, then revalidate in the background.
pass "$CC_DATA" "application/json" "assets/data/*.json" "assets/data/*/*.json"
# 4. Code.
pass "$CC_CODE" "" "assets/js/*" "assets/css/*"
# 5. Example files people can download.
pass "$CC_CODE" "application/vnd.localeditor.workflow+json" "*.leworkflow"
pass "$CC_CODE" "application/vnd.localeditor.project+zip" "*.leproject"
# 6. Pages and site files: always revalidate. The manifest needs its own type.
pass "$CC_PAGE" "application/manifest+json" "manifest.webmanifest"
pass "$CC_PAGE" "" "*.html" "robots.txt" "sitemap.xml" "llms.txt" "*.ico"
# 7. The service worker last: browsers check it for updates and it must point at files that exist.
pass "$CC_PAGE" "text/javascript; charset=utf-8" "sw.js"

if [ "$DELETE" = 1 ]; then
  echo "== Removing files that are no longer part of the site"
  # Files already uploaded above have the same size, so this pass only deletes (and uploads any file no class matched).
  run "${AWS[@]}" s3 sync . "$DEST" --delete "${NEVER[@]}" "${COMMON[@]}" --size-only
fi

if [ -n "$DIST" ]; then
  echo "== Invalidating CloudFront ($DIST)"
  # Pages, the manifest and the worker are what visitors fetch first; one wildcard path counts as one
  # invalidation path for billing. Assets are revalidated through their own short cache lifetimes.
  if [ "$DRY" = 1 ]; then
    printf '  would run:'; printf ' %q' "${AWS[@]}" cloudfront create-invalidation --distribution-id "$DIST" --paths "/*"; printf '\n'
  else
    run "${AWS[@]}" cloudfront create-invalidation --distribution-id "$DIST" --paths "/*" --query 'Invalidation.Id' --output text
  fi
fi
echo "== Done$([ "$DRY" = 1 ] && echo ' (dry run: nothing was changed)')"
